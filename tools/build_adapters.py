#!/usr/bin/env python3
"""Generate the installable host files for Claude Code and Codex from the canonical package sources.

Single responsibility: turn ``registry/*.json``, ``agents/*.md``, ``skills/aipt-method-*/``,
``workflows/*.md`` and ``entry/`` into ``dist/claude/`` and ``dist/codex/``, deterministically. The same
inputs always produce byte-identical outputs, so ``--check`` can detect a stale ``dist/``.

Usage:
    python3 tools/build_adapters.py            # rebuild dist/
    python3 tools/build_adapters.py --check    # exit 1 if dist/ differs from a fresh build

Standard library only (Python 3.11+).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSION = "0.1.0"
LICENSE_LINE = "See LICENSE_PENDING.md in the ai-product-team repository."

# Claude Code per-role tool allowlists by write scope. Mirrors adapters/claude/capabilities.json.
CLAUDE_TOOLS = {
    "proposal-only": (["Read", "Grep", "Glob"], ["Write", "Edit", "NotebookEdit", "Bash", "Agent"]),
    "assigned-worktree": (["Read", "Grep", "Glob", "Write", "Edit", "Bash"], ["Agent"]),
    "verification-sandbox": (["Read", "Grep", "Glob", "Bash"], ["Write", "Edit", "NotebookEdit", "Agent"]),
}
# Roles whose job requires reading public sources.
CLAUDE_EXTRA_TOOLS = {"source-researcher": ["WebSearch", "WebFetch"]}

SCOPE_RULE = {
    "proposal-only": "Do not create or edit files. Return each artifact's full content in your response; the root session writes it into the case folder.",
    "assigned-worktree": "Edit only the paths listed in the task envelope's output paths, inside the worktree or branch it names. Do not touch anything else.",
    "verification-sandbox": "Run the checks the envelope names and record exactly what ran. Do not edit tracked files.",
}


def load_json(rel: str) -> dict:
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def yaml_str(value: str) -> str:
    """Double-quoted YAML scalar, safe for any single-line text."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rewrite_repo_refs(text: str, agent_ids: set[str]) -> str:
    """Point repository role paths at their installed names, e.g. `agents/x.md` -> `aipt-x`."""
    def repl(m: re.Match) -> str:
        rid = m.group(1)
        return f"`aipt-{rid}`" if rid in agent_ids else m.group(0)
    return re.sub(r"`agents/([a-z0-9-]+)\.md`", repl, text)


def role_appendix(agent: dict, skill_names: list[str], host: str) -> str:
    skills = ", ".join(f"`{s}`" for s in skill_names)
    load = ("They are preloaded for you." if host == "claude"
            else "Load each one (for example `$" + skill_names[0] + "`) when a Method step names it.")
    return f"""

---

## Installed context

- You run as one role in the AI Product Team. The root session dispatched you with a task envelope. Answer only that task and return your response envelope as JSON, followed by each artifact.
- Do not start other agents or subagents. Put work for other roles in `requested_followups`.
- Your write scope is `{agent['write_scope']}`. {SCOPE_RULE[agent['write_scope']]}
- Shared methods: {skills}. {load}
- Where this file says "the controller" records or checks something, the root session does it in the case ledger described by the `aipt-start` skill. Paths such as `registry/…`, `docs/…` and `examples/…` refer to the ai-product-team repository.
"""


def claude_agent(agent: dict, team_name: str, body: str, skill_names: list[str]) -> str:
    tools, denied = CLAUDE_TOOLS[agent["write_scope"]]
    tools = tools + CLAUDE_EXTRA_TOOLS.get(agent["id"], [])
    desc = f"{agent['description']} AI Product Team, {team_name}: {agent['type'].replace('_', ' ')}. Dispatched by the aipt workflows, or directly for narrow work."
    fm = ["---", f"name: {agent['native_name']}", f"description: {yaml_str(desc)}",
          f"tools: {', '.join(tools)}", f"disallowedTools: {', '.join(denied)}", "skills:"]
    fm += [f"  - {s}" for s in skill_names]
    fm.append("---")
    return "\n".join(fm) + "\n\n" + body.rstrip() + role_appendix(agent, skill_names, "claude")


def codex_agent(agent: dict, team_name: str, body: str, skill_names: list[str]) -> str:
    instructions = body.rstrip() + role_appendix(agent, skill_names, "codex")
    if "'''" in instructions:
        raise ValueError(f"{agent['id']}: body contains ''' and cannot be a TOML literal string")
    desc = f"{agent['description']} AI Product Team, {team_name}: {agent['type'].replace('_', ' ')}."
    out = (f"# Generated by tools/build_adapters.py from agents/{agent['id']}.md. Do not edit.\n"
           f"name = {json.dumps(agent['native_name'])}\n"
           f"description = {json.dumps(desc, ensure_ascii=False)}\n"
           f"developer_instructions = '''\n{instructions}\n'''\n")
    tomllib.loads(out)  # fail the build if the TOML does not parse
    return out


def workflow_entry(wf: dict, agents: dict[str, dict], host: str) -> str:
    stage_rows = []
    for i, s in enumerate(wf["stages"], 1):
        role = s["role"]
        role_cell = f"`aipt-{role}`" if role in agents else f"{role} (the role that authored the frozen proposal)"
        when = f"`{s['conditional']}`" if s.get("conditional") else "always"
        gate = "review, independent" if s.get("independence_required") else ("review" if s.get("review") else "")
        stage_rows.append(f"| {i} | {s['title']} | {role_cell} | `{s['artifact']}` | {when} | {gate} |")
    reviews = [s["title"] for s in wf["stages"] if s.get("review")]
    indep = [s["title"] for s in wf["stages"] if s.get("independence_required")]
    cond = ", ".join(f"`aipt-{r}`" for r in wf["conditional_specialists"])
    desc = (f"{wf['id']} {wf['title']} Inputs: {'; '.join(wf['inputs'])}. "
            f"Returns: {'; '.join(wf['outputs'])}. Runs the AI Product Team {wf['name']} workflow from this session.")
    lines = ["---", f"name: {wf['entry_skill']}", f"description: {yaml_str(desc)}",
             f"license: {LICENSE_LINE}", "metadata:", f'  aipt_entry: "{wf["id"]}"', f'  aipt_version: "{VERSION}"', "---", "",
             f"# {wf['id']} · {wf['title']}", ""]
    if host == "claude":
        lines += ["Request: $ARGUMENTS", ""]
    lines += [
        "Run this workflow from the current session as the root orchestrator, following the `aipt-start` skill for routing, dispatch, gates and the case ledger. Load `aipt-start` first if it is not already loaded. The full procedure, stage by stage, is in `references/recipe.md`; read it before dispatching.",
        "",
        f"Manager: `aipt-{wf['manager']}` · Minimum risk: {wf['min_risk']} (raise it when the inputs or actions require it).",
        "", "## Inputs", ""] + [f"- {x}" for x in wf["inputs"]] + [
        "", "If an input is missing and would change the result, ask for it before dispatching.",
        "", "## Outputs", ""] + [f"- {x}" for x in wf["outputs"]] + [
        "", "## Work graph", "",
        "| # | Stage | Role | Artifact | Runs | Gate |", "|---|---|---|---|---|---|"] + stage_rows + [
        "",
        "Run stages in order, except where `references/recipe.md` marks two as parallel. Skip a stage only when a current accepted artifact of its type already exists in the case, and say so in the route plan. A stage marked with a condition runs only when that condition holds in the case.",
        "", "## Gates you may not skip", "",
        f"- Review stages: {', '.join(reviews) if reviews else 'none'}.",
        f"- Stages that need an independent reviewer (a fresh subagent that authored nothing it reviews): {', '.join(indep) if indep else 'none'}.",
        "- A manager's favorable review creates no authority and is not test evidence.",
        "", "## Conditional specialists", "",
        f"{cond}. Add one only for an identified missing dependency, review criterion or risk, and say why in the route plan.",
        "", "## Acceptance", ""] + [f"- {x}" for x in wf["acceptance"]] + [
        "", "## Fixture (unrun)", "",
        f"Scenario: {wf['fixture']['scenario']}", "",
        f"Expected behavior: {wf['fixture']['expected_behavior']}", ""]
    return "\n".join(lines)


def catalog_md(reg: dict, skills_by_id: dict[str, dict]) -> str:
    out = ["# AI Product Team: role catalog", "",
           "64 roles: three directors, one workflow orchestrator, and ten teams of six. Dispatch a role as the subagent or agent named in the first column.", ""]
    for team in reg["teams"]:
        members = [a for a in reg["agents"] if a["team"] == team["id"]]
        out += [f"## {team['name']}", "", "| Role | Type | Job | Write scope | Methods |", "|---|---|---|---|---|"]
        for a in members:
            methods = ", ".join("aipt-method-" + skills_by_id[s]["name"] for s in a["skill_ids"])
            out.append(f"| `{a['native_name']}` | {a['type'].replace('_', ' ')} | {a['description']} | {a['write_scope']} | {methods} |")
        out.append("")
    return "\n".join(out)


def workflows_md(wfs: dict) -> str:
    out = ["# AI Product Team: workflows", ""]
    for w in wfs["workflows"]:
        roles = " → ".join(f"{s['role']}{' (if ' + s['conditional'] + ')' if s.get('conditional') else ''}" for s in w["stages"])
        out += [f"## {w['id']} · {w['title']}", "",
                f"Entry skill `{w['entry_skill']}` · manager `{w['manager']}` · minimum risk {w['min_risk']}", "",
                f"Inputs: {'; '.join(w['inputs'])}.", "", f"Outputs: {'; '.join(w['outputs'])}.", "", f"Stages: {roles}.", ""]
    return "\n".join(out)


def build(dest: Path) -> dict:
    reg, sk, wfs = load_json("registry/agents.json"), load_json("registry/skills.json"), load_json("registry/workflows.json")
    agents = {a["id"]: a for a in reg["agents"]}
    teams = {t["id"]: t["name"] for t in reg["teams"]}
    skills_by_id = {s["id"]: s for s in sk["skills"]}
    ids = set(agents)
    files: dict[str, str] = {}

    for host, agent_dir, skill_dir in (("claude", ".claude/agents", ".claude/skills"), ("codex", ".codex/agents", ".agents/skills")):
        for a in reg["agents"]:
            body = rewrite_repo_refs((ROOT / "agents" / f"{a['id']}.md").read_text(encoding="utf-8"), ids)
            names = ["aipt-method-" + skills_by_id[s]["name"] for s in a["skill_ids"]]
            if host == "claude":
                files[f"{host}/{agent_dir}/{a['native_name']}.md"] = claude_agent(a, teams[a["team"]], body, names)
            else:
                files[f"{host}/{agent_dir}/{a['native_name']}.toml"] = codex_agent(a, teams[a["team"]], body, names)
        for s in sk["skills"]:
            src = ROOT / "skills" / f"aipt-method-{s['name']}"
            for f in sorted(p for p in src.rglob("*") if p.is_file() and p.name != ".DS_Store"):
                files[f"{host}/{skill_dir}/{src.name}/{f.relative_to(src).as_posix()}"] = rewrite_repo_refs(f.read_text(encoding="utf-8"), ids)
        start = ROOT / "entry" / "aipt-start"
        for f in sorted(p for p in start.rglob("*") if p.is_file() and p.name != ".DS_Store"):
            files[f"{host}/{skill_dir}/aipt-start/{f.relative_to(start).as_posix()}"] = f.read_text(encoding="utf-8")
        files[f"{host}/{skill_dir}/aipt-start/references/catalog.md"] = catalog_md(reg, skills_by_id)
        files[f"{host}/{skill_dir}/aipt-start/references/workflows.md"] = workflows_md(wfs)
        for w in wfs["workflows"]:
            files[f"{host}/{skill_dir}/{w['entry_skill']}/SKILL.md"] = workflow_entry(w, agents, host)
            recipe = rewrite_repo_refs((ROOT / "workflows" / f"{w['name']}.md").read_text(encoding="utf-8"), ids)
            files[f"{host}/{skill_dir}/{w['entry_skill']}/references/recipe.md"] = recipe

    manifest = {"package": "ai-product-team", "version": VERSION, "generated_by": "tools/build_adapters.py",
                "counts": {host: {"agents": sum(1 for k in files if k.startswith(f"{host}/") and "/agents/" in k),
                                  "skills": len({k.split('/')[3] for k in files if k.startswith(f"{host}/") and "/skills/" in k})}
                           for host in ("claude", "codex")},
                "files": {k: hashlib.sha256(v.encode("utf-8")).hexdigest() for k, v in sorted(files.items())}}
    for rel, text in files.items():
        p = dest / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8")
    # hashes must describe the bytes on disk
    manifest["files"] = {k: hashlib.sha256((dest / k).read_bytes()).hexdigest() for k in sorted(files)}
    (dest / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="compare dist/ with a fresh build; exit 1 on any difference")
    args = ap.parse_args(argv)
    dist = ROOT / "dist"
    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            fresh = build(Path(tmp))
            if not (dist / "MANIFEST.json").exists():
                print("dist/ is missing; run tools/build_adapters.py"); return 1
            current = json.loads((dist / "MANIFEST.json").read_text())
            on_disk = {p.relative_to(dist).as_posix() for p in dist.rglob("*") if p.is_file() and p.name not in ("MANIFEST.json", ".DS_Store")}
            stale = sorted(set(fresh["files"]) ^ on_disk) + sorted(k for k in fresh["files"] if current["files"].get(k) != fresh["files"][k] or (dist / k).exists() and hashlib.sha256((dist / k).read_bytes()).hexdigest() != fresh["files"][k])
            if stale:
                print("dist/ is stale:", *stale[:20], sep="\n  "); return 1
            print(f"dist/ is current: {len(fresh['files'])} files"); return 0
    if dist.exists():
        shutil.rmtree(dist)
    m = build(dist)
    print(json.dumps({"files": len(m["files"]), "counts": m["counts"]}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
